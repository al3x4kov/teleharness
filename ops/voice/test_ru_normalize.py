class Normalize(unittest.TestCase):
    def test_cases(self):
        bad = []
        for src, want in CASES:
            got = norm(src)
            if got != want:
                bad.append(f"{src!r}\n   got:  {got!r}\n   want: {want!r}")
        self.assertFalse(bad, "\n" + "\n".join(bad))

    def test_count(self):
        self.assertGreaterEqual(len(CASES), 60)

    def test_numbers_core(self):
        self.assertEqual(rn.cardinal(2026, "pre"), "двух тысячах двадцати шести")
        self.assertEqual(rn.cardinal(1, "acc", "f"), "одну")
        self.assertEqual(rn.cardinal(1000), "тысяча")
        self.assertEqual(rn.cardinal(21000, "nom"), "двадцать одна тысяча")
        self.assertEqual(rn.ordinal(2026, "pre"), "две тысячи двадцать шестом")
        self.assertEqual(rn.ordinal(3, "gen", "f"), "третьей")
        self.assertEqual(rn.ordinal(2000), "двухтысячный")
        self.assertEqual(rn.ordinal(40), "сороковой")
        self.assertEqual(rn.compound(24), "двадцатичетырёх")

    def test_never_raises_and_is_fast(self):
        import time
        junk = ["", "   ", "%%EOF %PDF-1.4", "a" * 600, "1" * 40, "...", "—", "x", "(((", "1.2.3.4.5.6",
                "Зомби: старые стенды 1912 (:4172), 6832 и цепочка 2220→5348→6256."]
        for t in junk:
            rn.normalize(t)
        rn.normalize("Прогрев: API.")
        t0 = time.perf_counter()
        for src, _ in CASES:
            rn.normalize(src)
        per = (time.perf_counter() - t0) * 1000 / len(CASES)
        self.assertLess(per, 50, f"{per:.1f} ms per phrase")


class FakeDict:
    def __init__(self, d):
        self.d = d
        self.db = True

    def lookup(self, words):
        return {w: self.d[w] for w in words if w in self.d}

    def fem(self, w):
        return None


class Stress(unittest.TestCase):
    def s(self, text, d=None):
        return rn.normalize(text, sd=FakeDict(d or {}))

    def test_vse_vsyo(self):
        self.assertEqual(self.s("Все готово."), "Всё готово.")
        self.assertEqual(self.s("Все тесты прошли."), "Все тесты прошли.")
        self.assertEqual(self.s("Это все."), "Это всё.")
        self.assertEqual(self.s("Мы все довольны."), "Мы все довольны.")
        self.assertEqual(self.s("Все работает."), "Всё работает.")
        self.assertEqual(self.s("Все в порядке."), "Всё в порядке.")

    def test_context_words(self):
        self.assertEqual(self.s("Уже готово."), "Уже" + A + " готово.")
        self.assertEqual(self.s("Не стоит волноваться."), "Не сто" + A + "ит волноваться.")
        self.assertEqual(self.s("Подписка стоит 20 долларов."), "Подписка сто" + A + "ит двадцать долларов.")
        self.assertEqual(self.s("С 5 по 10 ноября."), "С пятого по десятое ноября.")
        self.assertEqual(self.s("О чем речь?"), "О чём речь?")
        self.assertEqual(self.s("Перед запуском."), "Пе" + A + "ред запуском.")
        self.assertEqual(self.s("Ключ от замок"), "Ключ от замо" + A + "к")

    def test_dictionary(self):
        d = {"еще": "ещё", "логин": "логи" + A + "н"}
        self.assertEqual(self.s("Еще логин.", d), "Ещё логи" + A + "н.")
        self.assertEqual(self.s("ЛОГИН", d), "ЛОГИН", "upper-case acronyms are left to espeak")

    def test_terms_have_valid_marks(self):
        for k, v in rn.TERMS.items():
            self.assertNotIn("+", v, k)

    @unittest.skipUnless(HAS_DB, "ru_stress.db is not built")
    def test_real_db(self):
        out = rn.normalize("Еще отчет перед логин, в 21 строке и в 21 файле. Это се\u0301йлз.")
        self.assertIn("Ещё отчёт", out)
        self.assertIn("двадцати одной строке", out)
        self.assertIn("двадцати одном файле", out)
        self.assertIn("логи" + A + "н", out)
        self.assertIn("се" + A + "йлз", out, "a word with a mark is not looked up again")


